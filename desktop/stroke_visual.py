"""
Live stroke-motion view.

The Lovense local API is command-only — the device reports no position, so
this cannot be a measurement. It is a reconstruction of the motion that was
*commanded*:

  * the travel range comes straight from `Stroke:MIN-MAX` and is exact
  * the stroke rate is derived from the Thrusting value against a calibration
    figure (strokes per minute at maximum speed) the user can adjust

In preset mode the device generates its own pattern, so no motion is drawn.
"""

import math
import tkinter as tk

COL_BG = '#f5f6f8'
COL_BODY = '#dfe4ea'
COL_BODY_LINE = '#9aa4b2'
COL_SHAFT = '#3b434f'
COL_SHAFT_EDGE = '#232a33'
COL_STREAK = '#aeb7c2'
COL_WINDOW = '#7cbf6b'
COL_WINDOW_LINE = '#4d8f3f'
COL_GAUGE = '#e9ecf1'
COL_GAUGE_LINE = '#c3cbd6'
COL_MARK = '#d4635f'
COL_TEXT = '#2b313a'
COL_TEXT_DIM = '#6b7480'

MODE_PRESET = 'PRESET'


def _round_rect(x1, y1, x2, y2, r):
    return [
        x1 + r, y1, x2 - r, y1, x2, y1, x2, y1 + r, x2, y2 - r, x2, y2,
        x2 - r, y2, x1 + r, y2, x1, y2, x1, y2 - r, x1, y1 + r, x1, y1,
    ]


class StrokeVisualizer(tk.Canvas):
    """Vertical view of the stroke: how far it travels and how fast."""

    def __init__(self, parent, width=200, **kw):
        super().__init__(parent, width=width, bg=COL_BG, highlightthickness=0, **kw)
        self.phase = 0.0          # 0..1 through one full up-down cycle
        self.pos = 0.0            # current position, 0 = retracted, 100 = deep
        self.prev_pos = 0.0
        self.spm = 0.0

    # -- state ---------------------------------------------------------------

    def step(self, speed, max_speed, lo, hi, mode, spm_at_max, dt, length_mm=78.7):
        """Advance the simulated motion by dt seconds and redraw."""
        self.spm = (speed / max_speed) * spm_at_max if max_speed else 0.0
        self.length_mm = float(length_mm)
        moving = self.spm > 0.01 and mode != MODE_PRESET

        self.prev_pos = self.pos
        if moving:
            self.phase = (self.phase + (self.spm / 60.0) * dt) % 1.0
            # Sinusoidal travel: slow at both ends, fastest in the middle,
            # which is how a crank-driven stroker actually moves.
            travel = 0.5 - 0.5 * math.cos(2 * math.pi * self.phase)
            self.pos = lo + (hi - lo) * travel
        self._draw(lo, hi, mode, moving)

    # -- drawing -------------------------------------------------------------

    def _draw(self, lo, hi, mode, moving):
        self.delete('all')
        w = self.winfo_width() or 200
        h = self.winfo_height() or 460
        if w < 60 or h < 140:
            return

        top, bottom = 58, h - 74
        span = bottom - top
        mm = self.length_mm / 100.0        # millimetres per stroke unit
        body_x1, body_x2 = 24, w - 88
        gauge_x1, gauge_x2 = w - 72, w - 56

        def y_of(p):
            return top + (p / 100.0) * span

        self.create_text(w / 2, 13, text='Motion', font=('Segoe UI', 10, 'bold'),
                         fill=COL_TEXT)
        self.create_text(w / 2, 29, text='simulated from the sent command',
                         font=('Segoe UI', 7), fill=COL_TEXT_DIM)
        self.create_text(w / 2, 41,
                         text=f'0 = retracted   ·   100 = {self.length_mm:.0f} mm deep',
                         font=('Segoe UI', 7), fill=COL_TEXT_DIM)

        # --- device body ---------------------------------------------------
        self.create_polygon(_round_rect(body_x1, top - 8, body_x2, bottom + 8, 14),
                            smooth=True, fill=COL_BODY, outline=COL_BODY_LINE, width=2)

        # --- travel window inside the body ---------------------------------
        preset = (mode == MODE_PRESET)
        self.create_rectangle(body_x1 + 6, y_of(lo), body_x2 - 6, y_of(hi),
                              fill='#e6e9ee' if preset else '#eaf4e6',
                              outline=COL_GAUGE_LINE if preset else COL_WINDOW_LINE,
                              dash=(3, 3))

        if mode == MODE_PRESET:
            self.create_text((body_x1 + body_x2) / 2, (top + bottom) / 2,
                             text='preset\nrunning\n\nmotion is\ngenerated by\nthe device',
                             font=('Segoe UI', 8), fill=COL_TEXT_DIM, justify='center')
        else:
            # --- motion streak between the last frame and now ---------------
            if moving and abs(self.pos - self.prev_pos) > 0.5:
                y1, y2 = sorted((y_of(self.prev_pos), y_of(self.pos)))
                self.create_rectangle(body_x1 + 16, y1, body_x2 - 16, y2,
                                      fill=COL_STREAK, outline='')

            # --- the shaft: enters from the top, tip at the current position -
            tip = y_of(self.pos)
            cx = (body_x1 + body_x2) / 2
            half = (body_x2 - body_x1) / 2 - 12
            self.create_polygon(
                _round_rect(cx - half, top - 6, cx + half, tip, min(half, 18)),
                smooth=True, fill=COL_SHAFT, outline=COL_SHAFT_EDGE, width=1)
            # travel arrow next to the body
            self.create_line(body_x1 - 12, y_of(lo), body_x1 - 12, y_of(hi),
                             fill=COL_TEXT_DIM, width=2, arrow='both', arrowshape=(9, 11, 4))

        # --- gauge: window, current position, scale -------------------------
        self.create_rectangle(gauge_x1, top, gauge_x2, bottom,
                              fill=COL_GAUGE, outline=COL_GAUGE_LINE)
        self.create_rectangle(gauge_x1, y_of(lo), gauge_x2, y_of(hi),
                              fill='#ccd2da' if preset else COL_WINDOW,
                              outline=COL_GAUGE_LINE if preset else COL_WINDOW_LINE)
        for tick in (0, 25, 50, 75, 100):
            y = y_of(tick)
            self.create_line(gauge_x2, y, gauge_x2 + 4, y, fill=COL_GAUGE_LINE)
            self.create_text(gauge_x2 + 7, y, text=f'{tick * mm:.0f}', anchor='w',
                             font=('Segoe UI', 7), fill=COL_TEXT_DIM)
        self.create_text(gauge_x2 + 7, bottom + 13, text='mm', anchor='w',
                         font=('Segoe UI', 7, 'bold'), fill=COL_TEXT_DIM)
        if mode != MODE_PRESET:
            y = y_of(self.pos)
            self.create_line(gauge_x1 - 5, y, gauge_x2 + 1, y, fill=COL_MARK, width=2)

        # --- readouts -------------------------------------------------------
        travel_mm = (hi - lo) * mm
        if mode == MODE_PRESET:
            # The preset ignores our stroke window, so quoting it would be a lie
            self.create_text(w / 2, h - 52, text='device preset',
                             font=('Segoe UI', 10, 'bold'), fill=COL_TEXT)
            self.create_text(w / 2, h - 30, text='rate and depth\nare set by the toy',
                             font=('Segoe UI', 8), fill=COL_TEXT_DIM, justify='center')
            return
        rate = 'idle' if self.spm <= 0.01 else f'≈ {self.spm:.0f} strokes/min'
        self.create_text(w / 2, h - 52, text=rate, font=('Segoe UI', 10, 'bold'),
                         fill=COL_TEXT)
        self.create_text(w / 2, h - 34,
                         text=f'stroke {travel_mm:.0f} mm  ·  {travel_mm / 25.4:.2f} in',
                         font=('Segoe UI', 8), fill=COL_TEXT)
        self.create_text(w / 2, h - 18,
                         text=f'{lo * mm:.0f}-{hi * mm:.0f} mm   ({int(round(lo))}-{int(round(hi))})',
                         font=('Segoe UI', 8), fill=COL_TEXT_DIM)
